"""Suite and comparison Markdown reports (spec 18, Phase 5)."""

from __future__ import annotations

from pathlib import Path

from eval_lab.analysis.comparison import ComparisonResult
from eval_lab.analysis.weighted import SuiteAggregate


def _fmt(value: float | None, digits: int = 3) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def render_suite_report(suite_id: str, agg: SuiteAggregate, *, model_id: str | None) -> str:
    lines: list[str] = []
    lines.append(f"# Suite Report {suite_id}\n")
    lines.append(f"- System: `{model_id or 'unknown'}`")
    lines.append(f"- Tasks: {agg.task_count} (scored {agg.scored_tasks})")
    lines.append(f"- **Composite (weighted): {_fmt(agg.weighted_score)}**")
    lines.append(f"- Composite (unweighted): {_fmt(agg.unweighted_score)}")
    lines.append(f"- Pass rate (weighted): {_pct(agg.weighted_pass_rate)}")
    lines.append(f"- Pass rate (unweighted): {_pct(agg.unweighted_pass_rate)}")
    lines.append(f"- Weight sum: {_fmt(agg.weight_sum, 2)}\n")

    lines.append("## Per task\n")
    lines.append("| task | weight | score | passed | reps |")
    lines.append("|---|---|---|---|---|")
    for r in agg.per_task:
        passed = "--" if r.passed is None else ("pass" if r.passed else "FAIL")
        lines.append(
            f"| {r.task_id} | {_fmt(r.weight, 2)} | {_fmt(r.score)} | {passed} | {r.n_runs} |"
        )

    lines.append("\n## Label slices\n")
    slices = agg.slice("domain")
    if slices:
        lines.append("| domain | tasks | weighted | unweighted | pass (w/u) |")
        lines.append("|---|---|---|---|---|")
        for label, s in slices.items():
            lines.append(
                f"| {label} | {s.task_count} | {_fmt(s.weighted_score)} | "
                f"{_fmt(s.unweighted_score)} | "
                f"{_pct(s.weighted_pass_rate)} / {_pct(s.unweighted_pass_rate)} |"
            )
    else:
        lines.append("No domain labels resolved for the selected runs.")

    lines.append("\n---\n*Generated by eval-lab*")
    return "\n".join(lines)


def render_comparison_report(result: ComparisonResult) -> str:
    lines: list[str] = []
    lines.append(f"# Comparison Report: `{result.base_label}` vs `{result.candidate_label}`\n")
    lines.append(
        f"- Systems compared: base=`{result.base_label}`, candidate=`{result.candidate_label}`"
    )
    lines.append(f"- Matched tasks (sample size): {result.sample_size}")
    lines.append(f"- Mean paired delta (candidate - base): **{_fmt(result.mean_delta)}**")
    lines.append(f"- Median paired delta: {_fmt(result.median_delta)}")
    lines.append(f"- Bootstrap 95% CI: [{_fmt(result.ci[0])}, {_fmt(result.ci[1])}]")
    lines.append(f"- Win / tie / loss (candidate): {result.wins} / {result.ties} / {result.losses}")
    lines.append(
        "- Conclusion: "
        + (
            "candidate meaningfully better (CI excludes zero)"
            if result.significant and result.mean_delta > 0
            else (
                "candidate meaningfully worse (CI excludes zero)"
                if result.significant
                else "no significant difference (wide CI or small sample)"
            )
        )
    )

    transitions = result.failure_transitions
    if transitions:
        lines.append("\n## Failure transitions\n")
        lines.append("| Transition | Count |")
        lines.append("|---|---|")
        for key in ("stable_pass", "pass_to_fail", "fail_to_pass", "stable_fail"):
            lines.append(f"| {key} | {transitions.get(key, 0)} |")

    if result.regressions:
        lines.append("\n## Regressions (candidate worse than base)\n")
        lines.append("| task | base | candidate | delta | threshold |")
        lines.append("|---|---|---|---|---|")
        for r in result.regressions:
            lines.append(
                f"| {r.task_id} | {_fmt(r.base_score)} | {_fmt(r.candidate_score)} "
                f"| {_fmt(r.delta)} | {_fmt(r.threshold, 2)} |"
            )
    else:
        lines.append("\n## Regressions\nNone beyond threshold.\n")

    if result.improvements:
        lines.append("## Improvements (candidate better than base)\n")
        lines.append("| task | base | candidate | delta |")
        lines.append("|---|---|---|---|")
        for r in result.improvements:
            lines.append(
                f"| {r.task_id} | {_fmt(r.base_score)} | {_fmt(r.candidate_score)} | "
                f"{_fmt(r.delta)} |"
            )

    if result.resource_deltas:
        lines.append("\n## Resource deltas (candidate - base, mean)\n")
        lines.append("| resource | mean delta | tasks |")
        lines.append("|---|---|---|")
        for d in result.resource_deltas:
            lines.append(f"| {d.resource} | {_fmt(d.mean_delta, 4)} | {d.tasks} |")

    lines.append("\n---\n*Generated by eval-lab*")
    return "\n".join(lines)


def write_report(path: str | Path, content: str) -> Path:
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    return out
