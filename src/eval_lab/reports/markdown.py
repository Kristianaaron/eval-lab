"""Markdown report generation (spec 18)."""

from __future__ import annotations

from pathlib import Path


def render_run_report(result_dir: str | Path) -> str:
    """Render a Markdown report for a run directory (result.json + manifest.json)."""
    root = Path(result_dir)
    manifest = _read_json(root / "manifest.json")
    result = _read_json(root / "result.json")

    lines: list[str] = []
    lines.append(f"# Run Report {manifest.get('run_id', 'unknown')}\n")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    for key in (
        "task_id",
        "task_version",
        "model_id",
        "harness_id",
        "level",
        "status",
        "random_seed",
    ):
        lines.append(f"| {key} | {manifest.get(key, '')} |")
    lines.append(f"| duration_s | {result.get('duration_s', '')} |")
    lines.append(f"| aggregate | {result.get('aggregate', '')} |")
    lines.append(f"| passed | {result.get('passed', '')} |")

    scores_raw = result.get("scores")
    scores: list[dict[str, object]] = scores_raw if isinstance(scores_raw, list) else []
    if scores:
        lines.append("\n## Scores\n")
        lines.append("| scorer | score | passed | required |")
        lines.append("|---|---|---|---|")
        for s in scores:
            if not isinstance(s, dict):
                continue
            lines.append(
                f"| {s.get('scorer_id')} | {s.get('score')} | "
                f"{s.get('passed')} | {s.get('required')} |"
            )

    output_raw = result.get("output")
    output = output_raw.strip() if isinstance(output_raw, str) else ""
    if output:
        lines.append("\n## Output\n")
        lines.append("```text")
        lines.append(output[:2000])
        lines.append("```")

    error = result.get("error")
    if error:
        lines.append("\n## Error\n")
        lines.append(f"```text\n{error}\n```")

    lines.append("\n---\n*Generated by eval-lab*")
    return "\n".join(lines)


def write_run_report(result_dir: str | Path) -> Path:
    root = Path(result_dir)
    content = render_run_report(root)
    out = root / "report.md"
    out.write_text(content, encoding="utf-8")
    return out


def _read_json(path: Path) -> dict[str, object]:
    if not path.exists():
        return {}
    try:
        import json

        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}
